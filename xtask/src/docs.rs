//! `cargo xtask docs-cli [--check]` (ALK-US-0080): generate the two reference pages of the user
//! guide that must never drift from the code.
//!
//! - `docs/book/src/reference/cli.md`: the command tree, built by running the `alkahest` binary
//!   with `--help` for every command it lists. The binary is `ALKAHEST_DOCS_BIN`, else
//!   `target/debug/alkahest` (built first when missing).
//! - `docs/book/src/reference/configuration.md`: every configuration key, from the doc comments
//!   of the structs in `crates/alkahest-core/src/{config,pull}.rs`, with defaults taken from
//!   `alkahest config show --json`, and the environment variables found in `apply_env`.
//!
//! `--check` fails when a generated file differs from what is committed (CI uses it).

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;
use std::process::Command;

use anyhow::{Context, Result, anyhow, bail};

const CLI_PAGE: &str = "docs/book/src/reference/cli.md";
const CONFIG_PAGE: &str = "docs/book/src/reference/configuration.md";
const HEADER: &str = "<!-- Generated by `cargo xtask docs-cli`. Do not edit by hand. -->\n\n";

/// Flags every command accepts; their text is printed once, on the overview, not per command.
const GLOBAL_FLAGS: &[&str] = &[
    "--host",
    "--config",
    "--verbose",
    "--log-level",
    "--json",
    "--help",
    "--version",
];

/// Entry point: regenerate (or with `--check`, verify) both pages. Returns `Ok(false)` when
/// `--check` found a stale page.
pub fn run(root: &Path, args: &[String]) -> Result<bool> {
    let check = args.iter().any(|a| a == "--check");
    if let Some(bad) = args.iter().find(|a| a.as_str() != "--check") {
        bail!("unknown option `{bad}`");
    }
    let bin = binary(root)?;
    let pages = [
        (CLI_PAGE, render_cli(root, &bin)?),
        (CONFIG_PAGE, render_config(root, &bin)?),
    ];
    let mut ok = true;
    for (rel, content) in pages {
        let path = root.join(rel);
        if check {
            let current = fs::read_to_string(&path).unwrap_or_default();
            if current != content {
                eprintln!("xtask docs-cli: {rel} is stale; run `cargo xtask docs-cli`");
                ok = false;
            }
        } else {
            if let Some(dir) = path.parent() {
                fs::create_dir_all(dir)?;
            }
            fs::write(&path, content)?;
            println!("wrote {rel}");
        }
    }
    Ok(ok)
}

/// The binary to interrogate, built on demand.
fn binary(root: &Path) -> Result<std::path::PathBuf> {
    if let Some(p) = std::env::var_os("ALKAHEST_DOCS_BIN") {
        return Ok(p.into());
    }
    let bin = root.join("target/debug/alkahest");
    if !bin.exists() {
        let status = Command::new("cargo")
            .args([
                "build",
                "-p",
                "alkahest",
                "--no-default-features",
                "--locked",
            ])
            .current_dir(root)
            .status()
            .context("run cargo build")?;
        if !status.success() {
            bail!("cargo build -p alkahest failed");
        }
    }
    Ok(bin)
}

/// Runs the binary in a throw-away environment and returns stdout.
fn exec(bin: &Path, args: &[&str]) -> Result<String> {
    let home = std::env::temp_dir().join(format!("alkahest-docs-{}", std::process::id()));
    fs::create_dir_all(&home)?;
    let mut cmd = Command::new(bin);
    cmd.args(args).env_clear().env("ALKAHEST_HOME", &home);
    if let Some(path) = std::env::var_os("PATH") {
        cmd.env("PATH", path);
    }
    let out = cmd
        .output()
        .with_context(|| format!("run {}", bin.display()))?;
    let _ = fs::remove_dir_all(&home);
    if !out.status.success() {
        bail!(
            "`alkahest {}` failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

// --- CLI ----------------------------------------------------------------------------------------

/// One parsed `--help` page.
#[derive(Default)]
struct Help {
    about: String,
    usage: String,
    commands: Vec<(String, String)>,
    arguments: Vec<String>,
    options: Vec<String>,
}

/// An option entry's first flag, `--host` for `      --host <HOST[:PORT]>  Server ...`.
fn long_flag(entry: &str) -> Option<&str> {
    entry
        .split_whitespace()
        .flat_map(|w| w.split(','))
        .find(|w| w.starts_with("--"))
        .map(|w| w.trim_end_matches([',', ' ', '.']))
}

/// Splits a clap help page into its parts. Entries of Arguments and Options start with a dash
/// (or `<`) at an indent of at most six; deeper lines continue the previous entry.
fn parse_help(text: &str) -> Help {
    let mut help = Help::default();
    let mut section = "about";
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("Usage: ") {
            help.usage = rest.trim().to_string();
            section = "usage";
            continue;
        }
        match line.trim_end() {
            "Commands:" => {
                section = "commands";
                continue;
            }
            "Arguments:" => {
                section = "arguments";
                continue;
            }
            "Options:" => {
                section = "options";
                continue;
            }
            _ => {}
        }
        let indent = line.len() - line.trim_start().len();
        match section {
            "about" => {
                help.about.push_str(line);
                help.about.push('\n');
            }
            "commands" if indent == 2 => {
                let mut parts = line.trim().splitn(2, "  ");
                let name = parts.next().unwrap_or_default().to_string();
                let desc = parts.next().unwrap_or_default().trim().to_string();
                help.commands.push((name, desc));
            }
            "arguments" | "options" => {
                let list = if section == "arguments" {
                    &mut help.arguments
                } else {
                    &mut help.options
                };
                let starts = indent <= 6 && !line.trim().is_empty();
                if starts {
                    list.push(line.to_string());
                } else if let Some(last) = list.last_mut() {
                    last.push('\n');
                    last.push_str(line);
                }
            }
            _ => {}
        }
    }
    help.about = help.about.trim().to_string();
    help
}

/// Collapses runs of whitespace, so entries aligned differently still compare equal.
fn squash(entry: &str) -> String {
    entry.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Drops trailing blank lines of an entry.
fn tidy(entry: &str) -> String {
    entry.trim_end().to_string()
}

fn render_cli(root: &Path, bin: &Path) -> Result<String> {
    let _ = root;
    let top = parse_help(&exec(bin, &["--help"])?);
    let globals: BTreeMap<String, String> = top
        .options
        .iter()
        .filter_map(|e| long_flag(e).map(|f| (f.to_string(), tidy(e))))
        .collect();

    let mut out = String::from(HEADER);
    out.push_str("# Command reference\n\n");
    out.push_str(&format!("{}\n\n", top.about));
    out.push_str("```text\nalkahest [OPTIONS] <COMMAND>\n```\n\n");
    out.push_str("## Global options\n\nEvery command accepts these (`serve` binds `--host`, the client commands target it).\n\n```text\n");
    for e in &top.options {
        out.push_str(&tidy(e));
        out.push('\n');
    }
    out.push_str("```\n\n## Commands\n\n| Command | Purpose |\n|---|---|\n");
    for (name, desc) in top.commands.iter().filter(|(n, _)| n != "help") {
        out.push_str(&format!("| [`{name}`](#alkahest-{name}) | {desc} |\n"));
    }
    out.push('\n');

    for (name, _) in top.commands.iter().filter(|(n, _)| n != "help") {
        render_command(bin, &[name.as_str()], &globals, &mut out)?;
    }
    Ok(out)
}

fn render_command(
    bin: &Path,
    path: &[&str],
    globals: &BTreeMap<String, String>,
    out: &mut String,
) -> Result<()> {
    let mut args: Vec<&str> = path.to_vec();
    args.push("--help");
    let help = parse_help(&exec(bin, &args)?);
    let depth = "#".repeat(path.len() + 1);
    out.push_str(&format!("{depth} alkahest {}\n\n", path.join(" ")));
    if !help.about.is_empty() {
        out.push_str(&format!("{}\n\n", help.about));
    }
    out.push_str(&format!("```text\n{}\n```\n\n", help.usage));
    let subs: Vec<&(String, String)> = help.commands.iter().filter(|(n, _)| n != "help").collect();
    if !subs.is_empty() {
        out.push_str("| Subcommand | Purpose |\n|---|---|\n");
        for (name, desc) in &subs {
            out.push_str(&format!("| `{name}` | {desc} |\n"));
        }
        out.push('\n');
    }
    if !help.arguments.is_empty() {
        out.push_str("Arguments:\n\n```text\n");
        for a in &help.arguments {
            out.push_str(&tidy(a));
            out.push('\n');
        }
        out.push_str("```\n\n");
    }
    // Options that are the shared global ones, with the same text, are left out.
    let specific: Vec<&String> = help
        .options
        .iter()
        .filter(|e| match long_flag(e) {
            Some(f) if GLOBAL_FLAGS.contains(&f) => globals
                .get(f)
                .map(|g| squash(g) != squash(e))
                .unwrap_or(true),
            _ => true,
        })
        .collect();
    if !specific.is_empty() {
        out.push_str("Options (besides the global ones):\n\n```text\n");
        for e in specific {
            out.push_str(&tidy(e));
            out.push('\n');
        }
        out.push_str("```\n\n");
    }
    for (name, _) in subs {
        let mut next = path.to_vec();
        next.push(name.as_str());
        render_command(bin, &next, globals, out)?;
    }
    Ok(())
}

// --- configuration --------------------------------------------------------------------------------

/// A struct field with its documentation.
struct Field {
    name: String,
    ty: String,
    doc: String,
}

/// Parses `pub struct` blocks and `pub enum` variant lists out of a Rust source file.
fn parse_structs(
    src: &str,
    structs: &mut BTreeMap<String, Vec<Field>>,
    enums: &mut BTreeMap<String, Vec<String>>,
) {
    let mut doc: Vec<String> = Vec::new();
    let mut current: Option<(String, bool)> = None; // (name, is_struct)
    for line in src.lines() {
        let t = line.trim();
        if let Some(d) = t.strip_prefix("///") {
            doc.push(d.trim().to_string());
            continue;
        }
        if t.starts_with("#[") || t.is_empty() {
            if t.is_empty() && current.is_none() {
                doc.clear();
            }
            continue;
        }
        if current.is_none() {
            if let Some(rest) = t.strip_prefix("pub struct ") {
                let name = rest
                    .split([' ', '{'])
                    .next()
                    .unwrap_or_default()
                    .to_string();
                if t.ends_with('{') {
                    structs.entry(name.clone()).or_default();
                    current = Some((name, true));
                }
            } else if let Some(rest) = t.strip_prefix("pub enum ") {
                let name = rest
                    .split([' ', '{'])
                    .next()
                    .unwrap_or_default()
                    .to_string();
                enums.entry(name.clone()).or_default();
                current = Some((name, false));
            }
            doc.clear();
            continue;
        }
        let Some((name, is_struct)) = current.clone() else {
            continue;
        };
        if t == "}" {
            current = None;
            doc.clear();
            continue;
        }
        if is_struct {
            if let Some(rest) = t.strip_prefix("pub ")
                && let Some((field, ty)) = rest.split_once(':')
            {
                structs.entry(name).or_default().push(Field {
                    name: field.trim().trim_start_matches("r#").to_string(),
                    ty: ty.trim().trim_end_matches(',').to_string(),
                    doc: doc.join(" "),
                });
            }
        } else if let Some(variant) = t.split([',', ' ', '(']).next().filter(|v| !v.is_empty()) {
            enums.entry(name).or_default().push(variant.to_lowercase());
        }
        doc.clear();
    }
}

/// Flattens `config show --json` into `a.b.c -> rendered value`.
fn flatten(prefix: &str, v: &serde_json::Value, out: &mut BTreeMap<String, String>) {
    match v {
        serde_json::Value::Object(map) if !map.is_empty() => {
            for (k, v) in map {
                let key = if prefix.is_empty() {
                    k.clone()
                } else {
                    format!("{prefix}.{k}")
                };
                flatten(&key, v, out);
            }
        }
        other => {
            out.insert(prefix.to_string(), other.to_string());
        }
    }
}

/// Walks the struct graph from `Config`, emitting one row per leaf key.
#[allow(clippy::too_many_arguments)]
fn walk(
    ty: &str,
    prefix: &str,
    structs: &BTreeMap<String, Vec<Field>>,
    enums: &BTreeMap<String, Vec<String>>,
    defaults: &BTreeMap<String, String>,
    rows: &mut Vec<String>,
) {
    let Some(fields) = structs.get(ty) else {
        return;
    };
    for f in fields {
        let key = if prefix.is_empty() {
            f.name.clone()
        } else {
            format!("{prefix}.{}", f.name)
        };
        let base = f.ty.trim_start_matches("Option<").trim_end_matches('>');
        if structs.contains_key(base) {
            walk(base, &key, structs, enums, defaults, rows);
            continue;
        }
        if let Some(inner) =
            f.ty.strip_prefix("Vec<")
                .and_then(|s| s.strip_suffix('>'))
                .filter(|s| structs.contains_key(*s))
        {
            walk(inner, &format!("{key}[]"), structs, enums, defaults, rows);
            continue;
        }
        if let Some(inner) =
            f.ty.strip_prefix("BTreeMap<String, ")
                .and_then(|s| s.strip_suffix('>'))
        {
            walk(
                inner,
                &format!("{key}.<id>"),
                structs,
                enums,
                defaults,
                rows,
            );
            continue;
        }
        let mut ty_text =
            f.ty.replace("Option<", "optional ")
                .replace('>', "")
                .replace("Vec<", "list of ");
        if let Some(variants) = enums.get(base) {
            ty_text = format!(
                "one of {}",
                variants
                    .iter()
                    .map(|v| format!("`{v}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        let default = defaults
            .get(&key)
            .filter(|d| d.as_str() != "null")
            .map(|d| format!("`{}`", d.trim_matches('"')))
            .unwrap_or_else(|| "unset".to_string());
        rows.push(format!(
            "| `{key}` | {ty_text} | {default} | {} |",
            f.doc
                .replace("[`", "`")
                .replace("`]", "`")
                .replace('|', "\\|")
        ));
    }
}

/// `ALKAHEST_*` variables read by `apply_env`, with the key each one sets.
fn env_rows(src: &str) -> Vec<String> {
    let lines: Vec<&str> = src.lines().collect();
    let mut rows = Vec::new();
    for (i, line) in lines.iter().enumerate() {
        let Some(start) = line.find("get(\"ALKAHEST_") else {
            continue;
        };
        let rest = &line[start + 5..];
        let Some(end) = rest.find('"') else { continue };
        let var = &rest[..end];
        let key = lines[i + 1..(i + 14).min(lines.len())]
            .iter()
            .find_map(|l| {
                let at = l.find("self.")?;
                let tail = &l[at + 5..];
                let word: String = tail
                    .chars()
                    .take_while(|c| c.is_alphanumeric() || *c == '_' || *c == '.')
                    .collect();
                Some(word)
            })
            .unwrap_or_default();
        let key = match key.as_str() {
            "server.apply_host_spec" => {
                "`server.host` and `server.port` (`host`, `host:port`, `:port` or a URL)"
                    .to_string()
            }
            "" => String::new(),
            k => format!("`{k}`"),
        };
        rows.push(format!("| `{var}` | {key} |"));
    }
    rows
}

fn render_config(root: &Path, bin: &Path) -> Result<String> {
    let core = root.join("crates/alkahest-core/src");
    let mut structs = BTreeMap::new();
    let mut enums = BTreeMap::new();
    let config_src = fs::read_to_string(core.join("config.rs"))?;
    parse_structs(&config_src, &mut structs, &mut enums);
    parse_structs(
        &fs::read_to_string(core.join("pull.rs"))?,
        &mut structs,
        &mut enums,
    );

    let shown: serde_json::Value =
        serde_json::from_str(&exec(bin, &["config", "show", "--json"])?)?;
    let mut defaults = BTreeMap::new();
    flatten(
        "",
        shown
            .get("config")
            .ok_or_else(|| anyhow!("config show has no `config`"))?,
        &mut defaults,
    );

    let mut rows = Vec::new();
    walk("Config", "", &structs, &enums, &defaults, &mut rows);

    let mut out = String::from(HEADER);
    out.push_str("# Configuration reference\n\n");
    out.push_str(
        "Generated from the doc comments of `alkahest-core` and from `alkahest config show`.\n",
    );
    out.push_str("See [Configuration](../guide/configuration.md) for how the layers combine.\n\n");
    out.push_str("## Keys\n\nSections are TOML tables: `server.port` is `port` under `[server]`. A key shown as\n`unset` has no fixed default (it is derived, for example from the data directory).\n\n");
    out.push_str("| Key | Type | Default | Meaning |\n|---|---|---|---|\n");
    for r in rows {
        out.push_str(&r);
        out.push('\n');
    }
    out.push_str("\n## Environment variables that set a key\n\nThese win over every file.\n\n| Variable | Sets |\n|---|---|\n");
    for r in env_rows(&config_src) {
        out.push_str(&r);
        out.push('\n');
    }
    out.push('\n');
    Ok(out)
}

