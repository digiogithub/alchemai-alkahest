//! The Alkahest desktop app (`alkahest desktop`), built with GPUI through the gpui-kit facade.
//!
//! Layout and rules (AGENTS.md section 4, `design/README.md`):
//!
//! - Only the files under `src/ui/` (the facade) name the gpui-kit crate; every other module imports GPUI
//!   types from `crate::ui`. `cargo xtask check-deps` enforces it, so a gpui-kit upgrade only
//!   touches the facade.
//! - The window exists only with the `gui` feature (turned on by the binary's `desktop`
//!   feature). Without it the crate holds the GPUI-free parts: the generated design tokens
//!   ([`theme`]) and launch options, so the workspace builds and tests without GPUI.
//! - The app talks to the server only over HTTP through `alkahest-client`; it never runs
//!   inference in-process.
//! - Colours, sizes and type come from [`theme::tokens`], generated by `cargo xtask tokens`
//!   from `design/tokens.json`; views never hard-code them.

pub mod nav;
pub mod theme;

#[cfg(feature = "gui")]
mod app;
#[cfg(feature = "gui")]
mod fonts;
#[cfg(feature = "gui")]
mod tokio_bridge;
#[cfg(feature = "gui")]
pub mod ui;
#[cfg(feature = "gui")]
