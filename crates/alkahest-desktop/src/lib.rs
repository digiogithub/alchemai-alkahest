/// How `alkahest desktop` was asked to start.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LaunchOptions {
    /// Base URL of the configured server (`http://127.0.0.1:11435`). A `server_url` in the
    /// desktop settings file overrides it.
    pub server_url: String,
    /// API key from the environment (`ALKAHEST_API_KEY`); otherwise the OS keyring is asked.
    pub api_key: Option<String>,
    /// The desktop settings file (`<config dir>/desktop.toml`); `None` uses the defaults.
    pub settings_file: Option<std::path::PathBuf>,
    /// The `alkahest` executable used to start a local server; `None` never offers it.
    pub serve_program: Option<std::path::PathBuf>,
    /// Arguments placed before `serve` (for example `--config <file>`).
    pub serve_args: Vec<std::ffi::OsString>,
    /// Open the window, wait for the first frame, then exit with status 0 (CI smoke test).
    /// Skips the keyring, which could prompt for an unlock.
    pub smoke_test: bool,
}

impl Default for LaunchOptions {
    fn default() -> Self {
        Self {
            server_url: format!("http://127.0.0.1:{}", alkahest_client::DEFAULT_PORT),
            api_key: None,
            settings_file: None,
            serve_program: None,
            serve_args: Vec::new(),
            smoke_test: false,
        }
    }
}

/// Desktop start-up failures.
#[derive(Debug, thiserror::Error)]
pub enum DesktopError {
    /// The tokio runtime behind the HTTP client could not start.
    #[error("cannot start the async runtime: {0}")]
    Runtime(#[from] std::io::Error),
    /// The server URL is not valid.
    #[error("invalid server URL: {0}")]
    ServerUrl(String),
    /// The platform refused to open the main window (no display, no GPU driver).
    #[error("cannot open the main window: {0}")]
    Window(String),
    /// No frame was rendered within the smoke-test timeout.
    #[error("smoke test: no frame rendered within {0} s")]
    SmokeTimeout(u64),
}
